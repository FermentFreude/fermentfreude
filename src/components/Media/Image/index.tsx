'use client'

import type { ImageLoader, StaticImageData } from 'next/image'

import { cn } from '@/utilities/cn'
import NextImage from 'next/image'
import React from 'react'

import type { Props as MediaProps } from '../types'

function isValidImageSrc(src: unknown): src is string {
  if (typeof src !== 'string' || !src.trim()) return false
  if (/undefined|null|NaN/.test(src)) return false
  try {
    if (src.startsWith('/')) {
      new URL(src, 'https://example.com')
    } else {
      new URL(src)
    }
    return true
  } catch {
    return false
  }
}

/** Make a Payload url absolute-or-rooted the same way for the original and every pre-made size. */
function toSrc(url: string): string {
  if (url.startsWith('http') || url.startsWith('/')) return url
  const base = (process.env.NEXT_PUBLIC_SERVER_URL || '').replace(/\/$/, '')
  return base ? `${base}/${url.replace(/^\//, '')}` : `/${url}`
}

type Candidate = { url: string; width: number }

/**
 * Our own image "loader": instead of asking Vercel to resize (metered), pick the best copy that
 * Payload already made on upload (thumbnail 400 / card 800 / hero 1920 / original 2560).
 * For a requested width it returns the smallest copy that is at least that wide, so phones get the
 * small file, tablets the medium one, desktops the large one. New uploads get these copies
 * automatically (see collections/Media.ts), so nothing to do when adding images in the CMS.
 */
function makeLoader(candidates: Candidate[]): ImageLoader {
  const sorted = [...candidates].sort((a, b) => a.width - b.width)
  // Retina screens ask for 2-3x the CSS width; a copy ~45% narrower still looks sharp there,
  // so phones get the mobile copy instead of the next size up.
  return ({ width }) =>
    (sorted.find((c) => c.width >= width * 0.55) ?? sorted[sorted.length - 1]).url
}

export const Image: React.FC<MediaProps> = (props) => {
  const {
    alt: altFromProps,
    fill,
    height: heightFromProps,
    imgClassName,
    onClick,
    onError: onErrorFromProps,
    onLoad: onLoadFromProps,
    priority,
    resource,
    size: sizeFromProps,
    src: srcFromProps,
    width: widthFromProps,
  } = props

  const [, setIsLoading] = React.useState(true)

  let width: number | undefined | null
  let height: number | undefined | null
  let alt = altFromProps
  let src: StaticImageData | string = srcFromProps || ''
  let loader: ImageLoader | undefined

  // Extract src string from StaticImageData (static imports)
  if (typeof src === 'object' && src !== null && 'src' in src) {
    src = (src as StaticImageData).src
  }

  if (!src && resource && typeof resource === 'object') {
    const { alt: altFromResource, height: fullHeight, url, width: fullWidth } = resource

    width = widthFromProps ?? fullWidth
    height = heightFromProps ?? fullHeight
    alt = altFromResource

    if (url && typeof url === 'string') {
      src = toSrc(url)

      // Pre-made copies generated by Payload on upload (some old images may lack some of them)
      const candidates: Candidate[] = []
      const madeSizes = (
        resource as {
          sizes?: Record<string, { url?: string | null; width?: number | null } | undefined>
        }
      ).sizes
      for (const size of Object.values(madeSizes ?? {})) {
        if (size?.url && typeof size.width === 'number' && size.width > 0) {
          candidates.push({ url: toSrc(size.url), width: size.width })
        }
      }
      if (typeof fullWidth === 'number' && fullWidth > 0) {
        candidates.push({ url: src, width: fullWidth })
      }
      if (candidates.length > 1) loader = makeLoader(candidates)
    }
  }

  if (!isValidImageSrc(src)) {
    return (
      <div
        className={cn('bg-[#ECE5DE]', fill && 'absolute inset-0', imgClassName)}
        style={!fill ? { width: width ?? 200, height: height ?? 300 } : undefined}
        aria-hidden
      />
    )
  }

  // NOTE: this is used by the browser to determine which image to download at different screen sizes
  // Without an explicit size, assume full width
  const sizes = sizeFromProps || '100vw'

  return (
    <NextImage
      alt={alt || ''}
      className={cn(imgClassName)}
      fill={fill}
      height={!fill ? height || heightFromProps : undefined}
      onClick={onClick}
      onError={() => {
        if (typeof onErrorFromProps === 'function') {
          onErrorFromProps()
        }
      }}
      onLoad={() => {
        setIsLoading(false)
        if (typeof onLoadFromProps === 'function') {
          onLoadFromProps()
        }
      }}
      priority={priority}
      loader={loader}
      sizes={sizes}
      src={src}
      unoptimized={!loader}
      width={!fill ? width || widthFromProps : undefined}
    />
  )
}
