import { fulfilOnce } from '@/lib/paymentFulfilment'
import type { Voucher } from '@/payload-types'
import { getServerSideURL } from '@/utilities/getURL'
import type { Payload } from 'payload'

/* ═══════════════════════════════════════════════════════════════
 *  Voucher purchase → Voucher + Order (invoice) + voucher email
 *
 *  Shared by the success page (/api/voucher/confirm) and the Stripe
 *  webhook, so a paid voucher is created even when the buyer never
 *  comes back to the site (e.g. pays in the Klarna app and closes it).
 *  The caller has already verified with Stripe that the payment
 *  succeeded and is a voucher purchase.
 * ═══════════════════════════════════════════════════════════════ */

export type VoucherPurchaseResult = {
  code: string
  value: number
  deliveryMethod: Voucher['deliveryMethod']
  recipientEmail: string | null
  emailWarning: boolean
}

const toResult = (voucher: Voucher): VoucherPurchaseResult => ({
  code: voucher.code,
  value: voucher.value,
  deliveryMethod: voucher.deliveryMethod,
  recipientEmail: voucher.recipientEmail || null,
  emailWarning: Boolean(voucher.emailDeliveryFailed),
})

export async function fulfilVoucherPurchase(
  payload: Payload,
  {
    paymentKey,
    meta,
    amountCents,
    waitMs,
  }: {
    /** PaymentIntent ID (or legacy Checkout Session ID) — stored as stripeSessionId */
    paymentKey: string
    meta: Record<string, string>
    amountCents: number | null
    waitMs: number
  },
): Promise<VoucherPurchaseResult> {
  const findExisting = async () => {
    const existing = await payload.find({
      collection: 'vouchers',
      where: { stripeSessionId: { equals: paymentKey } },
      limit: 1,
      depth: 0,
      overrideAccess: true,
    })
    return existing.docs[0] ? toResult(existing.docs[0]) : null
  }

  return fulfilOnce(payload, paymentKey, {
    findExisting,
    waitMs,
    fulfil: () => createVoucherAndOrder(payload, { paymentKey, meta, amountCents }),
  })
}

async function createVoucherAndOrder(
  payload: Payload,
  {
    paymentKey,
    meta,
    amountCents,
  }: { paymentKey: string; meta: Record<string, string>; amountCents: number | null },
): Promise<VoucherPurchaseResult> {
  // ─── Order record first: it holds the invoice (Rechnung WEB) ──
  // Created before the voucher so the voucher email can link the invoice,
  // like the workshop confirmation does. Non-fatal: without it the voucher
  // and its email still go out, just without the invoice link.
  // skipOrderConfirmationEmail: the voucher email is the confirmation.
  let order: { id: string; downloadToken?: string | null } | null = null
  try {
    order = (await payload.create({
      collection: 'orders',
      overrideAccess: true,
      data: {
        items: [],
        customerEmail: meta.purchaserEmail,
        customerName: meta.purchaserName || undefined,
        status: 'completed',
        amount: amountCents ?? Math.round(Number(meta.amount) * 100),
        currency: 'EUR',
      },
      context: {
        skipOrderConfirmationEmail: true,
        skipRevalidate: true,
        skipAutoTranslate: true,
      },
    })) as unknown as { id: string; downloadToken?: string | null }
    payload.logger.info(`[voucher] Created order record ${order.id} for key ${paymentKey}`)
  } catch (orderError) {
    payload.logger.error(
      `[voucher] Failed to create order record for key ${paymentKey}: ${orderError instanceof Error ? orderError.message : String(orderError)}`,
    )
  }
  const receiptUrl = order?.downloadToken
    ? `${getServerSideURL().replace(/\/$/, '')}/api/orders/${order.id}/receipt?token=${order.downloadToken}`
    : undefined

  // ─── Create Voucher Record ───────────────────────────────────

  const voucher = await payload.create({
    collection: 'vouchers',
    overrideAccess: true,
    draft: false,
    data: {
      // code is auto-generated by beforeChange hook
      code: '',
      value: Number(meta.amount),
      status: 'active',
      purchaserName: meta.purchaserName || undefined,
      purchaserEmail: meta.purchaserEmail,
      recipientName: meta.recipientName || undefined,
      recipientEmail: meta.recipientEmail || undefined,
      personalNote: meta.personalNote || undefined,
      deliveryMethod:
        (meta.deliveryMethod as 'email-recipient' | 'email-self' | 'pdf' | 'email' | 'pickup') ||
        'email-self',
      stripeSessionId: paymentKey,
      redeemed: false,
    },
    // The purchase email (afterChange hook) adds the invoice link
    context: { receiptUrl },
  })

  payload.logger.info(`[voucher] Created voucher ${voucher.code} for key ${paymentKey}`)

  // ─── Link the order to its voucher (the invoice line reads it) ──
  if (order) {
    try {
      await payload.update({
        collection: 'orders',
        id: order.id,
        overrideAccess: true,
        data: { purchasedVoucher: voucher.id },
        context: { skipOrderConfirmationEmail: true, skipRevalidate: true, skipAutoTranslate: true },
      })
    } catch (linkError) {
      payload.logger.error(
        `[voucher] Order ${order.id} not linked to voucher ${voucher.code}: ${linkError instanceof Error ? linkError.message : String(linkError)}`,
      )
    }
  }

  return toResult(voucher)
}
